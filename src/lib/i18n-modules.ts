export function getLocalizedService(slug: string, lang: Language): Service {
  const base = services.find((s) => s.slug === slug) || services[0];
  const loc = localizedModules[lang]?.[slug];
  if (!loc) return base;
  return {
    ...base,
    title: loc.title || base.title,
    summary: loc.summary || base.summary,
    intro: loc.intro || base.intro,
    features: loc.features || base.features,
  };
}

export function getLocalizedServices(lang: Language): Service[] {
  return services.map((s) => getLocalizedService(s.slug, lang));
}
